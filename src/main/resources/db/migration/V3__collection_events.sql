-- 热门书预约队列调整：新增复本采购/分配的馆藏流转审计记录
-- 通用 SQL 子集，可同时在 PostgreSQL 与 H2(PostgreSQL 模式) 上由 Flyway 执行

CREATE TABLE collection_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bib_id           BIGINT REFERENCES bibs(id),
    item_id          BIGINT REFERENCES items(id),
    hold_id          BIGINT REFERENCES holds(id),
    from_library_id  BIGINT REFERENCES libraries(id),
    to_library_id    BIGINT REFERENCES libraries(id),
    -- ACQUIRE 新增复本到馆登记 / ALLOCATE 系统按队列平衡分配 /
    -- MANUAL_ADJUST 馆员人工改配（原因必填）
    event_type       VARCHAR(20) NOT NULL,
    -- ALLOCATE 时的分配方式：LOCAL 本馆即上架 / TRANSFER 跨馆调拨
    alloc_mode       VARCHAR(16),
    -- 操作人；系统自动分配记为 SYSTEM
    staff            VARCHAR(64) NOT NULL,
    reason           VARCHAR(512),
    detail           VARCHAR(1024),
    created_at       TIMESTAMP NOT NULL
);
CREATE INDEX idx_collection_events_bib ON collection_events(bib_id, created_at);
CREATE INDEX idx_collection_events_item ON collection_events(item_id);

